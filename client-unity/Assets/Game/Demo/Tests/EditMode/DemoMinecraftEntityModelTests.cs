        [TestCase(true)]
        [TestCase(false)]
        public void SpiderDefaultPoseSpreadsEightLegsDownwardAndIdleRetainsStandingPose(bool player)
        {
            var root = new GameObject("SpiderStanding");
            var material = new Material(Shader.Find("Standard"));
            try
            {
                Assert.That(DemoMinecraftModelFactory.TryBuild(root.transform, "cd_002", player, _ => material), Is.True);
                var body = root.transform.Find("Model/Bone_body0");
                var directions = new List<Vector3>();
                var sourceYaw = new[] { 45f, -45f, 22.5f, -22.5f, -22.5f, 22.5f, -45f, 45f };
                var sourceRoll = new[] { -45f, 45f, -33.3f, 33.3f, -33.3f, 33.3f, -45f, 45f };
                for (var index = 0; index < 8; index++)
                {
                    var leg = body.Find("Bone_leg" + index);
                    var direction = leg.localRotation * (index % 2 == 0 ? Vector3.right : Vector3.left);
                    var yaw = sourceYaw[index] * Mathf.Deg2Rad;
                    var roll = sourceRoll[index] * Mathf.Deg2Rad;
                    var side = index % 2 == 0 ? 1f : -1f;
                    // Independent source ZYX direction: yaw the mirrored X axis, then roll it.
                    var expected = side * new Vector3(Mathf.Cos(yaw) * Mathf.Cos(roll),
                        Mathf.Cos(yaw) * Mathf.Sin(roll), Mathf.Sin(yaw));
                    Assert.That(Vector3.Distance(direction, expected), Is.LessThan(0.0001f), "source leg " + index);
                    Assert.That(direction.y, Is.LessThan(-0.49f), "leg " + index + " must descend");
                    Assert.That(direction.z * (index < 4 ? 1 : -1), Is.GreaterThan(0.25f));
                    Assert.That(directions.All(prior => Vector3.Distance(prior, direction) > 0.1f), Is.True);
                    directions.Add(direction);
                }
                Assert.That(EncapsulateAll(root.GetComponentsInChildren<MeshRenderer>()).min.y, Is.EqualTo(0).Within(0.001f));
                var animator = root.GetComponent<DemoEntityIdleAnimator>();
                Assert.That(animator.TrackCount, Is.EqualTo(8));
                animator.SampleForAudit(0.23f);
                for (var index = 0; index < 8; index++)
                {
                    var direction = body.Find("Bone_leg" + index).localRotation * (index % 2 == 0 ? Vector3.right : Vector3.left);
                    Assert.That(Vector3.Angle(direction, directions[index]), Is.LessThanOrEqualTo(3.001f));
                }
                Assert.That(root.transform.eulerAngles.y, Is.EqualTo(player ? 180 : 0).Within(0.001f));
            }
            finally { Object.DestroyImmediate(root); Object.DestroyImmediate(material); }
        }

