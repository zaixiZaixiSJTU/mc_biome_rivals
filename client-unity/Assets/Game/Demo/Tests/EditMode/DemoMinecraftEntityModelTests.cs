        [TestCase(true, 0f)]
        [TestCase(false, 0f)]
        [TestCase(true, 0.23f)]
        [TestCase(false, 0.23f)]
        public void BlazeOriginalRodsOrbitInThreeSourceRings(bool player, float seconds)
        {
            var root = new GameObject("BlazeOrbit");
            var material = new Material(Shader.Find("Standard"));
            try
            {
                Assert.That(DemoMinecraftModelFactory.TryBuild(root.transform, "nt_003", player, _ => material), Is.True);
                var animator = root.GetComponent<DemoEntityIdleAnimator>();
                animator.SampleForAudit(seconds);
                for (var rod = 0; rod < 12; rod++)
                {
                    var ring = rod / 4;
                    var radius = ring == 0 ? 9f : ring == 1 ? 7f : 5f;
                    var rate = ring == 0 ? -360f : ring == 1 ? 108f : -180f;
                    var phase = rod % 4 * 90f + (ring == 0 ? 0f : ring == 1 ? 45f : 27f);
                    var angle = (phase + rate * seconds) * Mathf.Deg2Rad;
                    var height = (ring == 0 ? 2f : ring == 1 ? -2f : -11f) +
                        Mathf.Cos((rod * (ring == 2 ? 1.5f : 2f) + seconds * 20f) * 14.32f * Mathf.Deg2Rad);
                    var bone = root.transform.Find("Model/Bone_upperBodyParts" + rod);
                    Assert.That(Vector3.Distance(bone.localPosition,
                        new Vector3(-Mathf.Cos(angle) * radius, 24f + height, Mathf.Sin(angle) * radius) / 16f),
                        Is.LessThan(0.0001f), "original source rod position " + rod);
                    Assert.That(Vector3.Distance(bone.GetComponentInChildren<MeshFilter>().sharedMesh.bounds.center,
                        new Vector3(-1, -4, 1) / 16f), Is.LessThan(0.0001f), "do not rewrite source pivot " + rod);
                    Assert.That(Quaternion.Angle(bone.localRotation, Quaternion.identity), Is.LessThan(0.001f));
                }
                Assert.That(animator.TrackCount, Is.EqualTo(13));
                Assert.That(root.GetComponentsInChildren<MeshRenderer>().Length, Is.EqualTo(13));
                animator.SampleForAudit(0);
                Assert.That(EncapsulateAll(root.GetComponentsInChildren<MeshRenderer>()).min.y, Is.EqualTo(0.3f).Within(0.001f));
                Assert.That(root.transform.eulerAngles.y, Is.EqualTo(player ? 180 : 0).Within(0.001f));
            }
            finally { Object.DestroyImmediate(root); Object.DestroyImmediate(material); }
        }

