        // Independent physical-corner correspondence from pinned Blockbench box UV,
        // after reflecting source X into Unity. Numeric fixture is deliberately not
        // generated by the production UV-layout helper (64x32 atlas, 2x3x4 cube).
        private static Vector2[] ReferenceBoxCorners(int face, bool mirror)
        {
            var regions = new[] { new Vector4(11,13,9,10), new Vector4(17,13,15,10),
                new Vector4(15,13,11,10), new Vector4(9,13,5,10),
                new Vector4(11,10,9,6), new Vector4(13,6,11,10) };
            var region = regions[mirror && face == 2 ? 3 : mirror && face == 3 ? 2 : face];
            if (mirror) (region.x, region.z) = (region.z, region.x);
            return new[] { new Vector2(region.x,region.y), new Vector2(region.x,region.w),
                new Vector2(region.z,region.w), new Vector2(region.z,region.y) };
        }

        private static GameObject BuildBoxFixture(bool mirror, Material material)
        {
            var json = "{\"format_version\":\"1.8.0\",\"geometry.box\":{\"texturewidth\":64,\"textureheight\":32,\"bones\":[{\"name\":\"body\",\"pivot\":[0,0,0],\"cubes\":[{\"origin\":[-1,-1.5,-2],\"size\":[2,3,4],\"uv\":[5,6],\"mirror\":" + (mirror ? "true" : "false") + "}]}]}}";
            var root = new GameObject("SixFaceBox");
            Assert.That(DemoMinecraftEntityModelBuilder.TryBuild(root.transform,
                DemoMinecraftEntityGeometryParser.Parse(json, "geometry.box"),
                new DemoMinecraftEntityModelBuilder.BuildOptions { PrimaryTextureKey = "test", TextureWidth = 64,
                    TextureHeight = 32, MaterialProvider = _ => material }), Is.True);
            return root;
        }

        [TestCase(0,false)] [TestCase(1,false)] [TestCase(2,false)]
        [TestCase(3,false)] [TestCase(4,false)] [TestCase(5,false)]
        [TestCase(0,true)] [TestCase(1,true)] [TestCase(2,true)]
        [TestCase(3,true)] [TestCase(4,true)] [TestCase(5,true)]
        public void BoxUvMatchesIndependentPhysicalCorners(int face, bool mirror)
        {
            var material = new Material(Shader.Find("Standard"));
            var root = BuildBoxFixture(mirror, material);
            try
            {
                var uv = root.GetComponentInChildren<MeshFilter>().sharedMesh.uv;
                var expected = ReferenceBoxCorners(face, mirror);
                for (var corner = 0; corner < 4; corner++)
                    Assert.That(Vector2.Distance(uv[face * 4 + corner],
                        new Vector2(expected[corner].x / 64f, 1f - expected[corner].y / 32f)),
                        Is.LessThan(0.000001f), "face/corner " + face + "/" + corner);
            }
            finally { Object.DestroyImmediate(root); Object.DestroyImmediate(material); }
        }

        [TestCase(0,false)] [TestCase(1,false)] [TestCase(2,false)]
        [TestCase(3,false)] [TestCase(4,false)] [TestCase(5,false)]
        [TestCase(0,true)] [TestCase(1,true)] [TestCase(2,true)]
        [TestCase(3,true)] [TestCase(4,true)] [TestCase(5,true)]
        public void BoxUvSixFacesRenderAsymmetricAtlasThroughEntityShader(int face, bool mirror)
        {
            var texture = new Texture2D(64,32,TextureFormat.RGBA32,false,true)
                { filterMode = FilterMode.Point, wrapMode = TextureWrapMode.Clamp };
            for (var y = 0; y < 32; y++) for (var x = 0; x < 64; x++)
                texture.SetPixel(x,31-y,new Color((x+.5f)/64f,(y+.5f)/32f,.4f,1));
            texture.Apply();
            var material = new Material(Shader.Find("BiomeRivals/Demo/Entity")) { mainTexture = texture };
            var root = BuildBoxFixture(mirror, material);
            var cameraObject = new GameObject("SixFaceCamera");
            var target = new RenderTexture(128,128,24,RenderTextureFormat.ARGB32,RenderTextureReadWrite.Linear);
            var readback = new Texture2D(128,128,TextureFormat.RGBA32,false,true);
            var previous = RenderTexture.active;
            var fog = RenderSettings.fog;
            try
            {
                foreach (var transform in root.GetComponentsInChildren<Transform>()) transform.gameObject.layer = 29;
                var mesh = root.GetComponentInChildren<MeshFilter>().sharedMesh;
                mesh.colors = Enumerable.Repeat(Color.white,mesh.vertexCount).ToArray();
                // Fixed physical planes, not derived from mesh UV or production vertices.
                var a = new[] { new Vector3(-1,-1,-1),new Vector3(1,-1,1),new Vector3(-1,-1,1),
                    new Vector3(1,-1,-1),new Vector3(-1,1,-1),new Vector3(-1,-1,1) }[face];
                var b = new[] { new Vector3(-1,1,-1),new Vector3(1,1,1),new Vector3(-1,1,1),
                    new Vector3(1,1,-1),new Vector3(-1,1,1),new Vector3(-1,-1,-1) }[face];
                var d = new[] { new Vector3(1,-1,-1),new Vector3(-1,-1,1),new Vector3(-1,-1,-1),
                    new Vector3(1,-1,1),new Vector3(1,1,-1),new Vector3(1,-1,1) }[face];
                var normals = new[] { Vector3.back,Vector3.forward,Vector3.left,Vector3.right,Vector3.up,Vector3.down };
                var camera = cameraObject.AddComponent<Camera>();
                camera.enabled = false; camera.orthographic = true; camera.orthographicSize = .18f;
                camera.nearClipPlane = .01f; camera.farClipPlane = 4;
                camera.cullingMask = 1 << 29; camera.clearFlags = CameraClearFlags.SolidColor;
                camera.backgroundColor = Color.magenta; camera.allowHDR = false; camera.allowMSAA = false;
                camera.transform.position = normals[face];
                camera.transform.rotation = Quaternion.LookRotation(-normals[face], face < 4 ? Vector3.up : Vector3.forward);
                camera.targetTexture = target; RenderSettings.fog = false;
                camera.Render(); RenderTexture.active = target;
                readback.ReadPixels(new Rect(0,0,128,128),0,0); readback.Apply();
                var corners = ReferenceBoxCorners(face,mirror);
                foreach (var s in new[] { .25f,.75f }) foreach (var t in new[] { .25f,.75f })
                {
                    var physical = a + (d-a)*s + (b-a)*t;
                    var screen = camera.WorldToScreenPoint(Vector3.Scale(physical,new Vector3(1,1.5f,2))/16f);
                    var pixel = readback.GetPixel(Mathf.FloorToInt(screen.x),Mathf.FloorToInt(screen.y));
                    var uv = corners[0] + (corners[3]-corners[0])*s + (corners[1]-corners[0])*t;
                    Assert.That(pixel.r,Is.EqualTo(uv.x/64f).Within(.01f),"U face " + face);
                    Assert.That(pixel.g,Is.EqualTo(uv.y/32f).Within(.035f),"V face " + face);
                    Assert.That(pixel.b,Is.EqualTo(.4f).Within(.02f),"visible outward face " + face);
                }
            }
            finally
            {
                RenderTexture.active = previous; RenderSettings.fog = fog;
                Object.DestroyImmediate(cameraObject); Object.DestroyImmediate(root); Object.DestroyImmediate(material);
                Object.DestroyImmediate(texture); Object.DestroyImmediate(readback); target.Release(); Object.DestroyImmediate(target);
            }
        }

        private static string MirrorFixture(bool modern, bool boneMirror)
        {
            const string cube = "{\"origin\":[1,2,3],\"size\":[2,3,4],\"uv\":[5,6]";
            var bones = "\"bones\":[{\"name\":\"body\",\"pivot\":[0,0,0],\"mirror\":" +
                (boneMirror ? "true" : "false") + ",\"cubes\":[" + cube + "}," + cube + ",\"mirror\":false}," +
                cube + ",\"mirror\":true}]},{\"name\":\"child\",\"parent\":\"body\",\"pivot\":[0,4,0],\"cubes\":[" + cube + "}]}]";
            return modern ? "{\"format_version\":\"1.12.0\",\"minecraft:geometry\":[{\"description\":{\"identifier\":\"geometry.mirror\",\"texture_width\":64,\"texture_height\":32}," + bones + "}]}" :
                "{\"format_version\":\"1.8.0\",\"geometry.mirror\":{\"texturewidth\":64,\"textureheight\":32," + bones + "}}";
        }

